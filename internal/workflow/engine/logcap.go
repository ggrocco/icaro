// Chunk thresholds for the log index.
const (
	chunkBytes    = 64 << 10
	chunkInterval = time.Second
)

func (e *Engine) logPath(runID, stepID string, attempt int) string {
	return filepath.Join(e.cfg.LogsDir, runID, stepID+"."+strconv.Itoa(attempt)+".log")
}

// logCapture splits a step's stdout/stderr into lines, redacts secrets,
// appends them to the step's log file, indexes the file in log_chunks and
// publishes each line. It also keeps the (redacted) stdout for output
// capture. All writes come from one goroutine (stdcopy demultiplexing).
type logCapture struct {
	f       *os.File
	redact  *logs.Redactor
	offset  int64 // file size
	lines   int64 // lines emitted (including skipped ones on resume)
	skip    int64 // lines already in the file from before a re-attach
	partial [2][]byte

	stdout      bytes.Buffer
	stdoutLimit int64
	stdoutOver  bool

	seq         int
	chunkOffset int64
	chunkAt     time.Time

	ctx            context.Context
	st             *store.Store
	bus            *events.Bus
	runID, stepID  string
	attempt        int
	closed         bool
	logErr         func(msg string, err error)
	lastPersistErr error
}

// openLog prepares a step attempt's log. When resuming, the file is
// truncated to the last indexed offset and that many lines are skipped
// when the container's log stream is replayed from the start.
func (e *Engine) openLog(ctx context.Context, rx *runExec, row *store.StepRun, attempt int, resume bool) (*logCapture, error) {
	p := e.logPath(rx.run.ID, row.StepID, attempt)
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(p, os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	lc := &logCapture{
		f: f, redact: rx.redact, stdoutLimit: e.cfg.OutputLimit, chunkAt: time.Now(),
		ctx: context.WithoutCancel(ctx), st: e.d.Store, bus: e.d.Events,
		runID: rx.run.ID, stepID: row.StepID, attempt: attempt,
		logErr: func(msg string, err error) { e.log.Warn(msg, "run", rx.run.ID, "step", row.StepID, "err", err) },
	}
	if resume {
		if c, err := e.d.Store.LastLogChunk(ctx, rx.run.ID, row.StepID, attempt); err == nil {
			lc.offset, lc.skip, lc.seq, lc.chunkOffset = c.FileOffset, c.LineCount, c.Seq, c.FileOffset
		} else if !errors.Is(err, store.ErrNotFound) {
			_ = f.Close()
			return nil, err
		}
	}
	if err := f.Truncate(lc.offset); err != nil {
		_ = f.Close()
		return nil, err
	}
	if _, err := f.Seek(lc.offset, io.SeekStart); err != nil {
		_ = f.Close()
		return nil, err
	}
	return lc, nil
}

type streamWriter struct {
	lc     *logCapture
	stdout bool
}

func (w streamWriter) Write(p []byte) (int, error) {
	w.lc.write(w.stdout, p)
	return len(p), nil
}

func (lc *logCapture) writer(stdout bool) io.Writer { return streamWriter{lc: lc, stdout: stdout} }

func (lc *logCapture) write(stdout bool, p []byte) {
	i := 1
	if stdout {
		i = 0
	}
	buf := append(lc.partial[i], p...)
	for {
		n := bytes.IndexByte(buf, '\n')
		if n < 0 {
			break
		}
		lc.emit(buf[:n+1], stdout)
		buf = buf[n+1:]
	}
	lc.partial[i] = append([]byte(nil), buf...)
}

// line writes a message generated by the engine itself.
func (lc *logCapture) line(s string) { lc.emit([]byte(s+"\n"), false) }

func (lc *logCapture) emit(raw []byte, stdout bool) {
	lc.lines++
	red := lc.redact.Redact(append([]byte(nil), raw...))
	if stdout && !lc.stdoutOver {
		if int64(lc.stdout.Len()+len(red)) > lc.stdoutLimit {
			lc.stdoutOver = true
		} else {
			lc.stdout.Write(red)
		}
	}
	if lc.lines <= lc.skip {
		return
	}
	n, err := lc.f.Write(red)
	lc.offset += int64(n)
	if err != nil && lc.lastPersistErr == nil {
		lc.lastPersistErr = err
		lc.logErr("write step log", err)
	}
	lc.bus.Publish(events.Event{Type: events.TypeLog, RunID: lc.runID, Step: lc.stepID, Attempt: lc.attempt,
		Line: string(bytes.TrimRight(red, "\r\n")), Offset: lc.offset})
	if lc.offset-lc.chunkOffset >= chunkBytes || time.Since(lc.chunkAt) >= chunkInterval {
		lc.chunk()
	}
}

// chunk records the current offset/line count in the log index.
func (lc *logCapture) chunk() {
	if lc.offset == lc.chunkOffset && lc.seq > 0 {
		return
	}
	lc.seq++
	lc.chunkOffset, lc.chunkAt = lc.offset, time.Now()
	if err := lc.st.AddLogChunk(lc.ctx, &store.LogChunk{RunID: lc.runID, StepID: lc.stepID, Attempt: lc.attempt, Seq: lc.seq, FileOffset: lc.offset, LineCount: lc.lines}); err != nil {
		lc.logErr("index step log", err)
	}
}

// close flushes partial lines and the final index entry.
func (lc *logCapture) close() {
	if lc.closed {
		return
	}
	lc.closed = true
	for i, p := range lc.partial {
		if len(p) > 0 {
			lc.emit(append(p, '\n'), i == 0)
		}
	}
	lc.chunk()
	if err := lc.f.Close(); err != nil {
		lc.logErr("close step log", err)
	}
}
