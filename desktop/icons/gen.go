type point struct{ x, y float64 }

// Keep SVG curves and their flattened outlines together, so regeneration
// needs only the Go standard library rather than an external SVG renderer.
type path struct {
	d       strings.Builder
	outline []point
}

func (p *path) move(x, y float64) {
	fmt.Fprintf(&p.d, "M%g %g", x, y)
	p.outline = append(p.outline, point{x, y})
}

func (p *path) line(x, y float64) {
	fmt.Fprintf(&p.d, "L%g %g", x, y)
	p.outline = append(p.outline, point{x, y})
}

func (p *path) curve(x1, y1, x2, y2, x, y float64) {
	fmt.Fprintf(&p.d, "C%g %g %g %g %g %g", x1, y1, x2, y2, x, y)
	start := p.outline[len(p.outline)-1]
	for i := 1; i <= 32; i++ {
		t := float64(i) / 32
		u := 1 - t
		p.outline = append(p.outline, point{
			u*u*u*start.x + 3*u*u*t*x1 + 3*u*t*t*x2 + t*t*t*x,
			u*u*u*start.y + 3*u*u*t*y1 + 3*u*t*t*y2 + t*t*t*y,
		})
	}
}

func circle(x, y, r float64) *path {
	const k = 0.5522847498307936
	p := new(path)
	p.move(x+r, y)
	p.curve(x+r, y+k*r, x+k*r, y+r, x, y+r)
	p.curve(x-k*r, y+r, x-r, y+k*r, x-r, y)
	p.curve(x-r, y-k*r, x-k*r, y-r, x, y-r)
	p.curve(x+k*r, y-r, x+r, y-k*r, x+r, y)
	return p
}

type shape struct {
	path   *path
	fill   color.NRGBA
	mirror bool
}

func mark() []shape {
	gold := color.NRGBA{R: 0xf2, G: 0xb3, B: 0x3d, A: 255}
	ivory := color.NRGBA{R: 0xf8, G: 0xdf, B: 0x9d, A: 255}
	var shapes []shape
	feather := func(p *path, fill color.NRGBA) {
		shapes = append(shapes, shape{p, fill, false}, shape{p, fill, true})
	}

	// Four separated feathers form each upswept wing.
	p := new(path)
	p.move(23, 22)
	p.curve(23, 32, 31, 40, 43, 47)
	p.curve(28, 43, 16, 35, 23, 22)
	feather(p, ivory)

	p = new(path)
	p.move(19, 34)
	p.curve(22, 43, 31, 47, 43, 49)
	p.curve(29, 51, 15, 46, 19, 34)
	feather(p, gold)

	p = new(path)
	p.move(19, 46)
	p.curve(25, 52, 34, 53, 43, 52)
	p.curve(32, 59, 20, 59, 19, 46)
	feather(p, gold)

	p = new(path)
	p.move(24, 57)
	p.curve(31, 60, 39, 58, 45, 55)
	p.curve(39, 65, 29, 66, 24, 57)
	feather(p, gold)

	// A distinct head, raised arms and split legs make this a human figure.
	p = new(path)
	p.move(48, 47)
	p.curve(42, 47, 38, 44, 35, 40)
	p.line(32, 38)
	p.curve(35, 46, 39, 50, 44, 52)
	p.curve(47, 54, 48, 58, 47, 62)
	p.line(46.5, 66)
	p.line(48.5, 78)
	p.line(50, 66)
	p.line(51.5, 78)
	p.line(53.5, 66)
	p.line(53, 62)
	p.curve(52, 58, 53, 54, 56, 52)
	p.curve(61, 50, 65, 46, 68, 38)
	p.line(65, 40)
	p.curve(62, 44, 58, 47, 52, 47)
	shapes = append(shapes, shape{p, gold, false})
	shapes = append(shapes, shape{circle(50, 43, 2.8), gold, false})
	shapes = append(shapes, shape{circle(50, 29, 5.8), gold, false})
	return shapes
}

func main() {
	shapes := mark()
	writePNG("tray-template.png", raster(44, shapes, false, true))
	writePNG("tray.png", raster(64, shapes, false, false))
	writePNG("app.png", raster(1024, shapes, true, false))
	for _, name := range []string{"../../site/icaro.svg", "../../web/public/icaro.svg"} {
		if err := os.MkdirAll(filepath.Dir(name), 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(name, []byte(vector(shapes)), 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

func vector(shapes []shape) string {
	var out strings.Builder
	out.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="10 10 80 80" role="img" aria-labelledby="title desc">
  <!-- Generated by desktop/icons/gen.go. Artwork licensed CC BY 4.0. -->
  <title id="title">Ícaro</title>
  <desc id="desc">A gold Icarus with outstretched feathered wings ascends beneath the sun on a dark rounded tile.</desc>
  <rect x="10" y="10" width="80" height="80" rx="18" fill="#1d2333"/>
`)
	for _, s := range shapes {
		transform := ""
		if s.mirror {
			transform = ` transform="translate(100 0) scale(-1 1)"`
		}
		fmt.Fprintf(&out, "  <path d=\"%sZ\" fill=\"#%02x%02x%02x\"%s/>\n", s.path.d.String(), s.fill.R, s.fill.G, s.fill.B, transform)
	}
	out.WriteString("</svg>\n")
	return out.String()
}

// Supersample and average premultiplied colors to avoid dark fringes on
// transparent edges. The menu-bar versions omit the application tile.
func raster(size int, shapes []shape, tile, template bool) *image.NRGBA {
	const ss = 4
	n := size * ss
	canvas := image.NewNRGBA(image.Rect(0, 0, n, n))
	if tile {
		for y := 0; y < n; y++ {
			for x := 0; x < n; x++ {
				if inTile((float64(x)+0.5)/float64(n), (float64(y)+0.5)/float64(n)) {
					canvas.SetNRGBA(x, y, color.NRGBA{R: 0x1d, G: 0x23, B: 0x33, A: 255})
				}
			}
		}
	}
	for _, s := range shapes {
		points := make([]point, len(s.path.outline))
		for i, p := range s.path.outline {
			if s.mirror {
				p.x = 100 - p.x
			}
			p.x, p.y = p.x/100, p.y/100
			if !tile {
				p.x, p.y = 0.5+(p.x-0.5)/0.7, 0.5+(p.y-0.5)/0.7
			}
			points[i] = point{p.x * float64(n), p.y * float64(n)}
		}
		fill := s.fill
		if template {
			fill = color.NRGBA{A: 255}
		}
		fillPolygon(canvas, points, fill)
	}
	img := image.NewNRGBA(image.Rect(0, 0, size, size))
	for y := 0; y < size; y++ {
		for x := 0; x < size; x++ {
			var r, g, b, a int
			for sy := 0; sy < ss; sy++ {
				for sx := 0; sx < ss; sx++ {
					c := canvas.NRGBAAt(x*ss+sx, y*ss+sy)
					a += int(c.A)
					r += int(c.R) * int(c.A)
					g += int(c.G) * int(c.A)
					b += int(c.B) * int(c.A)
				}
			}
			if a > 0 {
				img.SetNRGBA(x, y, color.NRGBA{R: uint8(r / a), G: uint8(g / a), B: uint8(b / a), A: uint8(a / (ss * ss))})
			}
		}
	}
	return img
}

func fillPolygon(img *image.NRGBA, points []point, fill color.NRGBA) {
	minY, maxY := float64(img.Rect.Max.Y), 0.0
	for _, p := range points {
		minY, maxY = math.Min(minY, p.y), math.Max(maxY, p.y)
	}
	var intersections []float64
	for y := max(0, int(math.Ceil(minY-0.5))); y < min(img.Rect.Max.Y, int(math.Ceil(maxY-0.5))); y++ {
		py := float64(y) + 0.5
		intersections = intersections[:0]
		prev := points[len(points)-1]
		for _, p := range points {
			if (prev.y <= py && p.y > py) || (p.y <= py && prev.y > py) {
				intersections = append(intersections, prev.x+(py-prev.y)*(p.x-prev.x)/(p.y-prev.y))
			}
			prev = p
		}
		sort.Float64s(intersections)
		for i := 0; i+1 < len(intersections); i += 2 {
			left := max(0, int(math.Ceil(intersections[i]-0.5)))
			right := min(img.Rect.Max.X, int(math.Ceil(intersections[i+1]-0.5)))
			for x := left; x < right; x++ {
				img.SetNRGBA(x, y, fill)
			}
		}
	}
}

func inTile(x, y float64) bool {
	const m, rad = 0.1, 0.18
	if x < m || x > 1-m || y < m || y > 1-m {
		return false
	}
	cx := math.Max(m+rad-x, math.Max(0, x-(1-m-rad)))
	cy := math.Max(m+rad-y, math.Max(0, y-(1-m-rad)))
	return cx*cx+cy*cy <= rad*rad
}

func writePNG(name string, img image.Image) {
	f, err := os.Create(name)
	if err != nil {
		log.Fatal(err)
	}
	if err := png.Encode(f, img); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
}
