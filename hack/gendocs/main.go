// Command gendocs writes the CLI reference (docs/cli.md) from the cobra
// command tree, so the reference always matches the binary.
//
//	go run ./hack/gendocs            # rewrite docs/cli.md
//	go run ./hack/gendocs -check     # fail when it is out of date (CI)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"icaro/internal/cli"
)

func main() {
	out := flag.String("out", "docs/cli.md", "output file")
	check := flag.Bool("check", false, "fail if the file is out of date instead of writing it")
	flag.Parse()
	var buf bytes.Buffer
	render(&buf, cli.Tree())
	if *check {
		cur, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(cur, buf.Bytes()) {
			fmt.Fprintf(os.Stderr, "%s is out of date: run go run ./hack/gendocs\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render(b *bytes.Buffer, root *cobra.Command) {
	b.WriteString("# CLI reference\n\n")
	b.WriteString("<!-- Generated by `go run ./hack/gendocs`; do not edit. -->\n\n")
	b.WriteString("Every command also accepts the global flags `--config` (config file, default `$ICARO_CONFIG` or `~/.icaro/config/icaro.yaml`) and `--home` (state root, default `$ICARO_HOME` or `~/.icaro`).\n\n")
	var all []*cobra.Command
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, sub := range c.Commands() {
			if sub.Hidden || sub.Name() == "help" || sub.Name() == "completion" {
				continue
			}
			all = append(all, sub)
			walk(sub)
		}
	}
	walk(root)
	sort.SliceStable(all, func(i, j int) bool { return all[i].CommandPath() < all[j].CommandPath() })
	for _, c := range all {
		fmt.Fprintf(b, "## `%s`\n\n", c.CommandPath())
		desc := strings.TrimSpace(c.Long)
		if desc == "" {
			desc = c.Short
		}
		if desc != "" {
			b.WriteString(desc + "\n\n")
		}
		if c.Runnable() {
			fmt.Fprintf(b, "```text\n%s\n```\n\n", c.UseLine())
		}
		if len(c.Aliases) > 0 {
			fmt.Fprintf(b, "Aliases: %s\n\n", strings.Join(c.Aliases, ", "))
		}
		if flags := strings.TrimRight(c.NonInheritedFlags().FlagUsages(), "\n"); flags != "" {
			fmt.Fprintf(b, "```text\n%s\n```\n\n", flags)
		}
		if c.HasAvailableSubCommands() {
			b.WriteString("Subcommands:")
			for _, s := range c.Commands() {
				if s.IsAvailableCommand() {
					fmt.Fprintf(b, " `%s`", s.Name())
				}
			}
			b.WriteString("\n\n")
		}
	}
}
