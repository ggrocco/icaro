// Command licenses audits the licenses of the dependencies that ship in
// the icaro binary (Go modules linked into ./cmd/icaro) and in the web UI
// (npm production dependencies), and writes THIRD_PARTY_LICENSES.md.
//
//	go run ./hack/licenses              # write THIRD_PARTY_LICENSES.md
//	go run ./hack/licenses -check       # fail on a disallowed license or a stale file
//	go run ./hack/licenses -npm web -out web/THIRD_PARTY_LICENSES.md [-check]
//
// Allowed: MIT, BSD-2-Clause, BSD-3-Clause, Apache-2.0, ISC, MPL-2.0,
// Unlicense, 0BSD, CC0-1.0, BlueOak-1.0.0. Anything else (GPL, AGPL,
// LGPL, unknown) fails.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Allowed are the license identifiers compatible with shipping icaro.
var Allowed = map[string]bool{
	"MIT": true, "BSD-2-Clause": true, "BSD-3-Clause": true, "Apache-2.0": true, "ISC": true,
	"MPL-2.0": true, "Unlicense": true, "0BSD": true, "CC0-1.0": true, "BlueOak-1.0.0": true,
}

// Dep is one audited dependency.
type Dep struct {
	Name, Version, License string
}

func main() {
	check := flag.Bool("check", false, "fail if the output file is stale or a license is disallowed")
	npmDir := flag.String("npm", "", "audit npm production dependencies of this package directory instead of Go modules")
	out := flag.String("out", "THIRD_PARTY_LICENSES.md", "output file")
	pkg := flag.String("pkg", "./cmd/icaro", "Go package whose linked dependencies are audited")
	dir := flag.String("dir", "", "module directory to run in (desktop for the desktop app); -pkg and -out are relative to it")
	goos := flag.String("goos", "", "list the dependencies of this GOOS's build (with cgo), e.g. darwin for the macOS app")
	flag.Parse()
	if *dir != "" {
		if err := os.Chdir(*dir); err != nil {
			fmt.Fprintln(os.Stderr, "licenses:", err)
			os.Exit(2)
		}
	}

	var deps []Dep
	var err error
	title := "Go modules linked into " + *pkg
	if *dir != "" {
		title = "Go modules linked into " + *dir
	}
	if *goos != "" {
		title += " (" + *goos + ")"
	}
	if *npmDir != "" {
		title = "npm production dependencies of " + *npmDir
		deps, err = npmDeps(*npmDir)
	} else {
		deps, err = goDeps(*pkg, *goos)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(2)
	}
	doc := Render(title, deps)
	bad := Disallowed(deps)
	for _, d := range bad {
		fmt.Fprintf(os.Stderr, "disallowed license: %s %s: %s\n", d.Name, d.Version, d.License)
	}
	if *check {
		cur, _ := os.ReadFile(*out)
		if !bytes.Equal(cur, []byte(doc)) {
			fmt.Fprintf(os.Stderr, "%s is stale; run go run ./hack/licenses%s\n", *out, flagsFor(*npmDir, *dir, *pkg, *goos, *out))
			os.Exit(1)
		}
	} else if err := os.WriteFile(*out, []byte(doc), 0o644); err != nil { //nolint:gosec // a checked-in document
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(2)
	}
	if len(bad) > 0 {
		os.Exit(1)
	}
	fmt.Printf("%d dependencies, all allowed\n", len(deps))
}

func flagsFor(npm, dir, pkg, goos, out string) string {
	switch {
	case npm != "":
		return fmt.Sprintf(" -npm %s -out %s", npm, out)
	case dir != "":
		return fmt.Sprintf(" -dir %s -goos %s -pkg %s -out %s", dir, goos, pkg, out)
	}
	return ""
}

// Disallowed returns the deps whose license is not allowed.
func Disallowed(deps []Dep) []Dep {
	var out []Dep
	for _, d := range deps {
		if !licenseAllowed(d.License) {
			out = append(out, d)
		}
	}
	return out
}

// licenseAllowed accepts an identifier or an SPDX "A OR B" expression with
// at least one allowed alternative.
func licenseAllowed(l string) bool {
	l = strings.Trim(l, "() ")
	for _, alt := range strings.Split(l, " OR ") {
		if Allowed[strings.Trim(alt, "() ")] {
			return true
		}
	}
	return false
}

// Render produces the generated document.
func Render(title string, deps []Dep) string {
	sort.Slice(deps, func(i, j int) bool {
		if deps[i].Name != deps[j].Name {
			return deps[i].Name < deps[j].Name
		}
		return deps[i].Version < deps[j].Version
	})
	var b strings.Builder
	b.WriteString("# Third-party licenses\n\n")
	b.WriteString("Generated by `go run ./hack/licenses` — do not edit. ")
	b.WriteString(title + ".\n\n")
	b.WriteString("| Dependency | Version | License |\n|---|---|---|\n")
	for _, d := range deps {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", d.Name, d.Version, d.License)
	}
	return b.String()
}

type goPkg struct {
	Standard bool
	Module   *struct {
		Path    string
		Version string
		Dir     string
		Main    bool
		Replace *struct {
			Path, Version, Dir string
		}
	}
}

func goDeps(pkg, goos string) ([]Dep, error) {
	cmd := exec.Command("go", "list", "-deps", "-json", pkg) //nolint:gosec // a package path from the developer's own flag
	cmd.Stderr = os.Stderr
	if goos != "" {
		cmd.Env = append(os.Environ(), "GOOS="+goos, "CGO_ENABLED=1")
	}
	outp, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	dec := json.NewDecoder(bytes.NewReader(outp))
	seen := map[string]bool{}
	var deps []Dep
	for {
		var p goPkg
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, err
		}
		if p.Standard || p.Module == nil || p.Module.Main || seen[p.Module.Path] {
			continue
		}
		// A module replaced by a local directory is this repository's own
		// main module, seen from the desktop app's module.
		if r := p.Module.Replace; r != nil && r.Version == "" && (strings.HasPrefix(r.Path, ".") || filepath.IsAbs(r.Path)) {
			continue
		}
		seen[p.Module.Path] = true
		dir, version := p.Module.Dir, p.Module.Version
		if p.Module.Replace != nil {
			dir, version = p.Module.Replace.Dir, p.Module.Replace.Version
		}
		deps = append(deps, Dep{Name: p.Module.Path, Version: version, License: detectDir(dir)})
	}
	return deps, nil
}

var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying)(\.(md|txt))?$`)

func detectDir(dir string) string {
	if dir == "" {
		return "unknown (module not downloaded)"
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "unknown"
	}
	for _, e := range entries {
		if e.IsDir() || !licenseFile.MatchString(e.Name()) {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err == nil {
			return Classify(string(b))
		}
	}
	return "unknown (no LICENSE file)"
}

// Classify identifies a license text.
func Classify(text string) string {
	t := strings.Join(strings.Fields(strings.ToLower(text)), " ")
	switch {
	case strings.Contains(t, "gnu affero general public license"):
		return "AGPL"
	case strings.Contains(t, "gnu lesser general public license"):
		return "LGPL"
	case strings.Contains(t, "gnu general public license"):
		return "GPL"
	case strings.Contains(t, "apache license") && strings.Contains(t, "version 2.0"):
		return "Apache-2.0"
	case strings.Contains(t, "mozilla public license") && strings.Contains(t, "2.0"):
		return "MPL-2.0"
	case strings.Contains(t, "permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(t, "redistribution and use in source and binary forms"):
		if strings.Contains(t, "neither the name") || strings.Contains(t, "names of its contributors") || strings.Contains(t, "name of the copyright holder") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	case strings.Contains(t, "permission to use, copy, modify, and/or distribute this software"):
		if strings.Contains(t, "isc") {
			return "ISC"
		}
		return "0BSD"
	case strings.Contains(t, "this is free and unencumbered software released into the public domain"):
		return "Unlicense"
	case strings.Contains(t, "blue oak model license"):
		return "BlueOak-1.0.0"
	}
	return "unknown"
}

type npmNode struct {
	Version      string             `json:"version"`
	Dependencies map[string]npmNode `json:"dependencies"`
}

func npmDeps(dir string) ([]Dep, error) {
	cmd := exec.Command("npm", "ls", "--omit=dev", "--all", "--json")
	cmd.Dir = dir
	outp, err := cmd.Output()
	if err != nil && len(outp) == 0 {
		return nil, fmt.Errorf("npm ls: %w", err)
	}
	var root npmNode
	if err := json.Unmarshal(outp, &root); err != nil {
		return nil, fmt.Errorf("npm ls output: %w", err)
	}
	seen := map[string]bool{}
	var deps []Dep
	var walk func(m map[string]npmNode)
	walk = func(m map[string]npmNode) {
		for name, n := range m {
			// An unmet optional peer is listed without a version: it is
			// not installed and does not ship.
			if n.Version == "" {
				continue
			}
			// npm prints a package's children only at one of its
			// occurrences ("deduped" elsewhere), so always descend.
			if key := name + "@" + n.Version; !seen[key] {
				seen[key] = true
				deps = append(deps, Dep{Name: name, Version: n.Version, License: npmLicense(dir, name)})
			}
			walk(n.Dependencies)
		}
	}
	walk(root.Dependencies)
	return deps, nil
}

func npmLicense(dir, name string) string {
	b, err := os.ReadFile(filepath.Join(dir, "node_modules", name, "package.json"))
	if err != nil {
		return "unknown (not installed)"
	}
	var pj struct {
		License  any `json:"license"`
		Licenses []struct {
			Type string `json:"type"`
		} `json:"licenses"`
	}
	if err := json.Unmarshal(b, &pj); err != nil {
		return "unknown"
	}
	switch l := pj.License.(type) {
	case string:
		return l
	case map[string]any:
		if t, ok := l["type"].(string); ok {
			return t
		}
	}
	if len(pj.Licenses) > 0 {
		var ts []string
		for _, l := range pj.Licenses {
			ts = append(ts, l.Type)
		}
		return strings.Join(ts, " OR ")
	}
	return "unknown"
}
